"""E6: PCA and K-Means on each station's hourly ticket-timing profile (Figure 4/F4).

Hypothesis: stations mostly differ in WHEN they record tickets (timing), not how
many (volume) -- PC1's loadings-by-hour either look like a timing contrast or they
don't, and we say which.
Usage: PYTHONPATH=. python experiments/e6_unsup.py
"""
import matplotlib.pyplot as plt
import pandas as pd

from parksight import config as C
from parksight.research import style
from parksight.research.unsup import hourly_profile_matrix, run_kmeans, run_pca

OUT = C.ROOT / "results" / "tables"
K_RANGE = range(2, 7)


def archetype_name(mean_profile: pd.Series) -> str:
    """A short, data-driven label from where a cluster's mean profile peaks."""
    peak = int(mean_profile.idxmax())
    active = mean_profile[mean_profile >= mean_profile.max() * 0.5].index
    span = int(active.max()) - int(active.min()) if len(active) else 0
    if span >= 12:
        return f"all-day (peak {peak:02d}:00)"
    if peak <= 7:
        return f"pre-dawn (peak {peak:02d}:00)"
    if peak <= 13:
        return f"late-morning (peak {peak:02d}:00)"
    return f"afternoon-or-later (peak {peak:02d}:00)"


def tidy(explained_var, loadings_pc1, sil, scores, labels):
    rows = []
    for i, v in enumerate(explained_var):
        rows.append(dict(section="explained_variance", key=f"PC{i + 1}", metric="ratio", value=v))
    for hour, v in loadings_pc1.items():
        rows.append(dict(section="pc1_loadings", key=hour, metric="loading", value=v))
    for k, v in sil.items():
        rows.append(dict(section="silhouette", key=k, metric="score", value=v))
    merged = scores.merge(labels.rename("cluster"), left_on="police_station", right_index=True)
    for _, r in merged.iterrows():
        for metric in ("PC1", "PC2", "cluster"):
            rows.append(dict(section="station", key=r["police_station"], metric=metric, value=r[metric]))
    return pd.DataFrame(rows)


def figure4(explained_var, loadings_pc1):
    style.apply()
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(6.0, 2.4))
    pcs = range(1, len(explained_var) + 1)
    ax1.bar(pcs, 100 * explained_var, color=style.PALETTE[0])
    ax1.set_xlabel("principal component")
    ax1.set_ylabel("% variance explained")
    ax1.set_xticks(list(pcs)[:6])

    ax2.plot(loadings_pc1.index, loadings_pc1.values, color=style.PALETTE[0], linewidth=2)
    ax2.axhline(0, color="black", linewidth=0.6)
    ax2.set_xlabel("hour (IST)")
    ax2.set_ylabel("PC1 loading")
    ax2.set_xticks(range(0, 24, 4))
    fig.tight_layout()
    return style.savefig(fig, "F4_pca_kmeans")


def main():
    tickets = pd.read_parquet(C.PROCESSED / "violations_clean.parquet",
                              columns=["police_station", "created_ist"])
    profile = hourly_profile_matrix(tickets)

    scores, explained_var, components = run_pca(profile)
    loadings_pc1 = pd.Series(components[0], index=profile.columns)

    km = run_kmeans(profile, k_range=K_RANGE, seed=0)

    archetypes = {}
    for cl in sorted(km["labels"].unique()):
        stations = km["labels"][km["labels"] == cl].index
        archetypes[cl] = archetype_name(profile.loc[stations].mean())

    OUT.mkdir(parents=True, exist_ok=True)
    out = tidy(explained_var, loadings_pc1, km["silhouette"], scores, km["labels"])
    header = (
        "# E6: PCA and K-Means on each station's 24-hour ticket-timing profile. "
        "Generated by experiments/e6_unsup.py.\n"
        "# section=explained_variance  share of variance each PC explains (key=PC1,PC2,...).\n"
        "# section=pc1_loadings        PC1's loading at each hour (key=hour 0-23); the PCA hypothesis check.\n"
        "# section=silhouette          silhouette score per candidate k (key=k, 2..6); higher is better.\n"
        "# section=station             per-station PC1, PC2 score and chosen K-Means cluster id "
        f"(best_k={km['best_k']}); key=police_station.\n"
        f"# Archetypes at best_k={km['best_k']}: "
        + "; ".join(f"cluster {c}={n} (n={sum(km['labels'] == c)})" for c, n in archetypes.items()) + "\n"
    )
    csv_path = OUT / "E6_unsup.csv"
    csv_path.write_text(header)
    out.to_csv(csv_path, index=False, mode="a")

    fig_path = figure4(explained_var, loadings_pc1)

    print(f"Explained variance (PC1..PC3): {[round(100 * v, 1) for v in explained_var[:3]]}%")
    print(f"Best k by silhouette: {km['best_k']} (silhouette={km['silhouette'][km['best_k']]:.3f})")
    for c, n in archetypes.items():
        print(f"  cluster {c}: {n}, n={int((km['labels'] == c).sum())} stations")
    print(f"Figure 4 -> {fig_path}")


if __name__ == "__main__":
    main()
